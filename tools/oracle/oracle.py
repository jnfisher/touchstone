#!/usr/bin/env python3
"""Oracle command line.

    python3 -I tools/oracle/oracle.py parse            # parse MME's formula modules, report errors
    python3 -I tools/oracle/oracle.py report [--json]  # unbound names and procedures that run without shims
    python3 -I tools/oracle/oracle.py call PROC [ARG...]   # call one procedure with simple arguments
    python3 -I tools/oracle/oracle.py gen FAMILY|--all [--out DIR]   # write fixtures/rules/<family>.json
    python3 -I tools/oracle/oracle.py check [-j N] [FAMILY...]    # regenerate into a temp dir, diff with the committed fixtures

MME source comes from the cache that tools/mme-fetch.sh fills (never from the repository).
"""
import argparse
import json
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

from vbi.interp import Interpreter  # noqa: E402
from vbi.parser import parse_file  # noqa: E402
from vbi.errors import VBSyntaxError, VBError, OracleUnbound  # noqa: E402
from vbi import analysis  # noqa: E402

FORMULA_MODULES = ["modMMudFunc.bas", "modSyntaxsFunc.bas", "clsMonsterAttackSim.cls", "modExpPerHour.bas"]
DECL_MODULES = ["modMain.bas", "modMMudDatabase.bas"]


def mme_dir():
    env = os.environ.get("MME_DIR")
    if env:
        return env
    script = os.path.join(HERE, "..", "mme-fetch.sh")
    out = subprocess.run(["bash", script], capture_output=True, text=True, check=True).stdout.strip()
    return out.splitlines()[-1]


def load_all(mme, procs_of_decl_modules=False):
    it = Interpreter()
    for f in DECL_MODULES:
        it.load_file(os.path.join(mme, f), load_procs=procs_of_decl_modules)
    for f in FORMULA_MODULES:
        it.load_file(os.path.join(mme, f))
    it.ensure_ready()
    return it


def cmd_parse(args):
    mme = mme_dir()
    bad = 0
    for f in FORMULA_MODULES + DECL_MODULES:
        path = os.path.join(mme, f)
        try:
            m = parse_file(path)
            print("%-28s ok  procedures=%d vars=%d types=%d enums=%d" % (
                f, len(m.procs), len(m.vars), len(m.types), len(m.enums)))
        except VBSyntaxError as e:
            bad += 1
            print("%-28s ERROR %s" % (f, e))
    return 1 if bad else 0


def build_report(it):
    use = analysis.analyze(it, {"modmmudfunc", "modsyntaxsfunc", "clsmonsterattacksim", "modexpperhour"})
    keys = list(use.calls.keys())
    clean = analysis.transitive_clean(use, keys)
    procs = {}
    for m in it.modules.values():
        if m.load_procs:
            for p in m.ast.procs:
                procs[analysis.proc_key(p)] = p
    results = {}
    for k in sorted(keys):
        p = procs[k]
        if k in clean:
            status, detail = analysis.smoke_run(it, p)
            results[k] = (status, detail)
    return use, clean, results


def report_markdown(out, results):
    L = []
    w = L.append
    w("# Oracle report: what the formula modules need from shims")
    w("")
    w("Generated by `python3 -I tools/oracle/oracle.py report --md` (names only, no MME source).")
    w("")
    w("- procedures in the four formula modules: %d" % out["procedures_total"])
    w("- free of unbound names (static call-graph closure): %d" % out["statically_clean"])
    w("- ran to completion with simple arguments: %d" % len(out["run_ok"]))
    w("")
    w("## Procedures that run with no shims")
    by = {}
    for k in out["run_ok"]:
        m, _, n = k.partition(".")
        by.setdefault(m, []).append(n)
    for m, names in sorted(by.items()):
        w("")
        w("**%s** (%d): %s" % (m, len(names), ", ".join(names)))
    w("")
    w("## Free of unbound names but failed on the simple arguments")
    for k, v in sorted(out["clean_but_failed"].items()):
        w("- %s: %s" % (k, v))
    w("")
    w("## Intrinsics the oracle does not run")
    for k, v in sorted(out["intrinsics"].items()):
        w("- %s: %s" % (k, ", ".join(v)))
    w("")
    w("## Recordsets (declared globals of type Recordset)")
    for k, v in out["recordsets"].items():
        w("- **%s**: fields %s; dynamic field names %s; members used %s" % (
            k, ", ".join(v["fields"]) or "-", ", ".join(v["dynamic"]) or "-", ", ".join(v["members"]) or "-"))
    w("")
    w("## Forms and controls")
    for k, v in out["forms"].items():
        w("- **%s**: %s" % (k, "; ".join("%s%s" % (c, " (" + ", ".join(p) + ")" if p else "") for c, p in v.items())))
    w("")
    w("## Globals read (declared in modMain / modMMudDatabase; the scenario sets them)")
    w(", ".join("%s As %s" % (k, v) for k, v in sorted(out["globals_read"].items())))
    w("")
    w("## Globals written")
    w(", ".join("%s As %s" % (k, v) for k, v in sorted(out["globals_written"].items())) or "-")
    w("")
    w("## Procedures and names of modules that are not loaded")
    for k, v in sorted(out["other_procedures"].items()):
        w("- %s (from %s)" % (k, ", ".join(v)))
    w("")
    w("Plain names (not called with arguments), possibly zero-argument functions or constants:")
    for k, v in sorted(out["other_names"].items()):
        if k not in out["other_procedures"]:
            w("- %s (from %s)" % (k, ", ".join(v)))
    return "\n".join(L) + "\n"


def cmd_report(args):
    mme = mme_dir()
    it = load_all(mme)
    use, clean, results = build_report(it)
    ok = sorted(k for k, (s, _) in results.items() if s == "ok")
    other = {k: v for k, v in results.items() if v[0] != "ok"}
    out = {
        "procedures_total": len(use.calls),
        "statically_clean": len(clean),
        "run_ok": ["%s.%s" % k for k in ok],
        "clean_but_failed": {"%s.%s" % k: "%s %s" % v for k, v in other.items()},
        "intrinsics": {k: sorted(v) for k, v in sorted(use.intrinsics.items())},
        "recordsets": {k: {"fields": sorted(v["fields"]), "dynamic": sorted(v["dynamic"]),
                           "members": sorted(v["members"])} for k, v in sorted(use.recordsets.items())},
        "objects": {k: {"type": v["type"], "members": sorted(v["members"])} for k, v in sorted(use.objects.items())},
        "forms": {k: {c: sorted(p) for c, p in sorted(v["controls"].items())} for k, v in sorted(use.forms.items())},
        "globals_read": {v[0]: v[1] for v in use.globals_read.values()},
        "globals_written": {v[0]: v[1] for v in use.globals_written.values()},
        "other_procedures": {k: sorted(v) for k, v in sorted(use.other_procs.items())},
        "other_names": {k: sorted(v) for k, v in sorted(use.other_names.items())},
    }
    if args.json:
        print(json.dumps(out, indent=1, sort_keys=True))
        return 0
    if args.md:
        print(report_markdown(out, results), end="")
        return 0
    print("procedures: %d, statically free of unbound names: %d, ran ok with simple args: %d" % (
        out["procedures_total"], out["statically_clean"], len(ok)))
    for k, v in sorted(other.items()):
        print("  clean but %s: %s.%s %s" % (v[0], k[0], k[1], v[1]))
    print("recordsets:", len(out["recordsets"]), "forms:", len(out["forms"]), "globals:",
          len(out["globals_read"]), "other procs:", len(out["other_procedures"]),
          "other names:", len(out["other_names"]), "objects:", len(out["objects"]))
    return 0


def cmd_call(args):
    mme = mme_dir()
    it = load_all(mme)
    vals = []
    for a in args.args:
        try:
            vals.append(int(a))
        except ValueError:
            try:
                vals.append(float(a))
            except ValueError:
                vals.append(a)
    try:
        print(repr(it.call(args.proc, *vals)))
    except OracleUnbound as e:
        print("unbound:", e.name, e.detail or "")
        return 2
    except VBError as e:
        print("VB error", e.number, e.description)
        return 3
    return 0


def cmd_gen(args):
    import time
    import harness
    fams = harness.families() if args.all else [args.family]
    if not fams or fams == [None]:
        print("name a family or use --all; known: %s" % ", ".join(harness.families()))
        return 2
    out = args.out or harness.rules_dir()
    os.makedirs(out, exist_ok=True)
    for fam in fams:
        t = time.time()
        data = harness.build_fixture(fam)
        with open(os.path.join(out, fam + ".json"), "wb") as f:
            f.write(data)
        print("%s: %d bytes in %.1fs -> %s" % (fam, len(data), time.time() - t, out))
    return 0


def _check_worker(fam):
    """Build one family's fixture in a worker process; returns (family, bytes, seconds)."""
    import time
    import harness
    t = time.time()
    return fam, harness.build_fixture(fam), time.time() - t


def cmd_check(args):
    import difflib
    import time
    import harness
    fams = args.families or harness.families()
    jobs = args.jobs or min(4, os.cpu_count() or 1)
    jobs = max(1, min(jobs, len(fams)))
    bad = 0
    t0 = time.time()

    def report(fam, data, secs):
        committed = os.path.join(harness.rules_dir(), fam + ".json")
        if not os.path.exists(committed):
            print("%s: MISSING fixtures/rules/%s.json" % (fam, fam))
            return 1
        with open(committed, "rb") as f:
            old = f.read()
        if old == data:
            print("%s: current (%.1fs)" % (fam, secs), flush=True)
            return 0
        print("%s: STALE" % fam)
        diff = difflib.unified_diff(old.decode().splitlines(), data.decode().splitlines(),
                                    "committed", "regenerated", lineterm="", n=0)
        for i, line in enumerate(diff):
            if i >= 40:
                print("  ... (diff truncated)")
                break
            print("  " + line[:200])
        return 1

    if jobs == 1:
        for fam in fams:
            bad += report(*_check_worker(fam))
    else:
        import multiprocessing
        # Start the biggest scenarios first so the slowest family does not begin last; each result
        # is compared as it arrives, so the output order follows completion.
        order = sorted(fams, key=lambda f: -os.path.getsize(os.path.join(harness.scenario_dir(), f + ".json"))
                       if os.path.exists(os.path.join(harness.scenario_dir(), f + ".json")) else 0)
        with multiprocessing.get_context("fork").Pool(jobs) as pool:
            for fam, data, secs in pool.imap_unordered(_check_worker, order, chunksize=1):
                bad += report(fam, data, secs)
    print("checked %d families in %.1fs (jobs=%d)" % (len(fams), time.time() - t0, jobs))
    return 1 if bad else 0


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("parse")
    r = sub.add_parser("report")
    r.add_argument("--json", action="store_true")
    r.add_argument("--md", action="store_true")
    c = sub.add_parser("call")
    c.add_argument("proc")
    c.add_argument("args", nargs="*")
    g = sub.add_parser("gen")
    g.add_argument("family", nargs="?")
    g.add_argument("--all", action="store_true")
    g.add_argument("--out")
    k = sub.add_parser("check")
    k.add_argument("families", nargs="*")
    k.add_argument("--jobs", "-j", type=int, default=0, help="worker processes (default min(4, cpu count))")
    a = ap.parse_args(argv)
    return {"parse": cmd_parse, "report": cmd_report, "call": cmd_call, "gen": cmd_gen, "check": cmd_check}[a.cmd](a)


if __name__ == "__main__":
    sys.exit(main())
