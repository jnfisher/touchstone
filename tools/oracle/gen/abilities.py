"""Writes fixtures/scenarios/abilities.json from the stock database (stdlib, deterministic).

    python3 -I tools/oracle/gen/abilities.py [DB.sqlite]

Rows are chosen so every ability number seen in a table appears in at least one chosen row, plus
rows with the odd shapes (stray value beside ability 0, full slot arrays, repeated abilities; first 3 of each) and
every 60th row for spread. Trailing all-zero slots are dropped from the recorded row; the Rust
test pads it back to the table's slot count.
"""
import json
import os
import sqlite3
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
DEFAULT_DB = os.path.expanduser(
    "~/.cache/touchstone/mdb/eba20f06af8dc08df755eb6dcd9763b023794f12e809cbab6762236d64d7345f.sqlite")
SPEC = [("race", "Races", "RaceHasAbility", 10), ("class", "Classes", "ClassHasAbility", 10),
        ("spell", "Spells", "SpellHasAbility", 10), ("item", "Items", "ItemHasAbility", 20)]


def rows(c, t, n):
    cols = ['"Number"'] + ['"Abil-%d"' % i for i in range(n)] + ['"AbilVal-%d"' % i for i in range(n)]
    out = []
    for r in c.execute('select %s from "%s" order by "Number"' % (",".join(cols), t)):
        out.append((r[0], [[r[1 + i] or 0, r[1 + n + i] or 0] for i in range(n)]))
    return out


def choose(rs, n, everything):
    if everything:
        return list(rs)
    picked, seen, odd_taken = {}, set(), {}
    for num, ab in rs:
        own = {a for a, _ in ab if a}
        odd = []
        if any(a == 0 and v != 0 for a, v in ab):
            odd.append("stray")
        if all(a for a, _ in ab):
            odd.append("full")
        if len([a for a, _ in ab if a]) != len(own):
            odd.append("dup")
        take = [o for o in odd if odd_taken.get(o, 0) < 3]
        for o in take:
            odd_taken[o] = odd_taken.get(o, 0) + 1
        if own - seen or take:
            picked[num] = ab
            seen |= own
    for i, (num, ab) in enumerate(rs):
        if i % 60 == 0:
            picked[num] = ab
    return sorted(picked.items())


def main():
    c = sqlite3.connect(sys.argv[1] if len(sys.argv) > 1 else DEFAULT_DB)
    eff = sorted(set(range(-5, 1201)) | {1001, 1004, 2000, 5000, 32767, -32768})
    grids = [
        {"name": "effects", "axes": {"n": eff}, "case": {"proc": "AbilityEffectsCharStats", "args": ["$n"]}},
        {"name": "slot0", "axes": {"n": eff}, "case": {"proc": "GetAbilityStatSlot", "args": ["$n", 0]}},
        {"name": "slot5", "axes": {"n": list(range(-2, 200)) + [1001, 5000], "v": [5]},
         "case": {"proc": "GetAbilityStatSlot", "args": ["$n", "$v"]}},
    ]
    cases = []
    for kind, t, proc, n in SPEC:
        rs = rows(c, t, n)
        union = sorted({a for _, ab in rs for a, _ in ab if a})
        miss = [0, -1, 9999] if kind != "item" else [0, -1, -2, 9999]
        top = rs[-1][0]
        for num, ab in choose(rs, n, kind in ("race", "class")):
            own = []
            for a, _ in ab:
                if a and a not in own:
                    own.append(a)
            if kind in ("race", "class"):
                alist = sorted(set(union) | set(miss) | {3, -3})
            else:
                alist = own + [m for m in miss if m not in own]
                alist += [u for u in union if u not in own][:1]
            steps = [{"call": proc, "args": [num, a], "as": ("a%d" % a) if a >= 0 else ("m%d" % -a)}
                     for a in alist]
            probe = own[0] if own else 1
            steps += [{"call": proc, "args": [0, probe], "as": "num0"},
                      {"call": proc, "args": [-1, probe], "as": "numneg"},
                      {"call": proc, "args": [top + 1000, probe], "as": "numhigh"}]
            k = len(ab)
            while k and ab[k - 1] == [0, 0]:
                k -= 1
            cases.append({"id": "%s-%05d" % (kind, num),
                          "row": {"kind": kind, "number": num, "abilities": ab[:k]}, "steps": steps})
    scn = {"family": "abilities", "database": True,
           "description": "Ability lookups on race, class, spell and item rows (stock), AbilityEffectsCharStats and GetAbilityStatSlot over ability numbers.",
           "notes": ["Generated by tools/oracle/gen/abilities.py. Each lookup case carries the row it reads in inputs.row (trailing zero slots dropped) so the Rust test needs no database.",
                     "GetAbilityStatSlot also fills sText through GetAbilityStats; that text is P3-07's and is not compared here."],
           "tolerance": {"default": 0}, "grids": grids, "cases": cases}
    with open(os.path.join(ROOT, "fixtures", "scenarios", "abilities.json"), "w") as f:
        json.dump(scn, f, separators=(",", ":"))
        f.write("\n")


main()
